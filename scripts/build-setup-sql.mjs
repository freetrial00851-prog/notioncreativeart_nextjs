/**
 * Builds supabase/full-setup.sql by concatenating migration files in order.
 * Run: node scripts/build-setup-sql.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs'
import { join } from 'path'

const SUPABASE_DIR = join(import.meta.dirname, '..', 'supabase')

/** Run order — each file is idempotent where possible (IF NOT EXISTS). */
const ORDER = [
  'schema.sql',
  'storage-setup.sql',
  'site-settings.sql',
  'seed-categories.sql',
  'features-2.sql',
  'cart.sql',
  'newsletter.sql',
  'homepage-layout.sql',
  'categories-parent-migration.sql',
  'categories-image-migration.sql',
  'billing-address.sql',
  'billing-address-full.sql',
  'materials-field.sql',
  'product-seo-fields.sql',
  'products-soft-delete-migration.sql',
  'checkout-mode.sql',
  'cart-numeric-variant-id.sql',
  'wishlist-count.sql',
  'image-pipeline-migration.sql',
  'free-pattern-direct-download-migration.sql',
  'name-change-cooldown-migration.sql',
  'also-bought-rpc.sql',
  'product-slug-existence-check.sql',
  'purchases-unique-constraint-fix.sql',
  'purchases-insert-policy-free-only.sql',
  'CRITICAL-fix-profile-privilege-escalation.sql',
  'patterns-bucket-read-policy-v2-secure.sql',
  'fix-null-images.sql',
  'fix-google-profile-names.sql',
  'fix-repurchase-overwrite.sql',
  'cascade-product-delete.sql',
  'rate-limit-table.sql',
  'newsletter-close-direct-insert.sql',
  'catchup-migration.sql',
  'products-bundle-fields.sql',
  'products-pdf-filename.sql',
  'abandoned-cart-reminder.sql',
  'grants-api-access.sql',
  'seed-initial-data.sql',
]

const CONTINUE_FROM = 'purchases-unique-constraint-fix.sql'

const parts = [
  '-- AUTO-GENERATED by scripts/build-setup-sql.mjs — do not edit by hand\n',
  '-- Target: notioncreativeart_nextjs (anlsellghialszuuvipw)\n\n',
]

const continueParts = [
  '-- AUTO-GENERATED continue script — run ONLY if full-setup.sql failed partway through\n',
  '-- PREREQUISITE: public.purchases must already exist (schema.sql section completed).\n',
  '-- If you see "relation public.purchases does not exist", run full-setup.sql instead.\n\n',
  `do $$
begin
  if not exists (
    select 1 from information_schema.tables
    where table_schema = 'public' and table_name = 'purchases'
  ) then
    raise exception 'public.purchases does not exist. Run supabase/full-setup.sql first — not this continue script.';
  end if;
end $$;\n\n`,
]

let includeContinue = false

for (const file of ORDER) {
  if (file === CONTINUE_FROM) includeContinue = true
  const path = join(SUPABASE_DIR, file)
  try {
    const chunk = `\n-- ═══ ${file} ═══\n` + readFileSync(path, 'utf8') + '\n'
    parts.push(chunk)
    if (includeContinue) continueParts.push(chunk)
    console.log('included:', file)
  } catch {
    console.warn('skipped (missing):', file)
  }
}

const out = join(SUPABASE_DIR, 'full-setup.sql')
writeFileSync(out, parts.join(''))
console.log(`\nWrote ${out} (${parts.join('').length} bytes)`)

const continueOut = join(SUPABASE_DIR, 'full-setup-continue.sql')
writeFileSync(continueOut, continueParts.join(''))
console.log(`Wrote ${continueOut} (${continueParts.join('').length} bytes)`)
